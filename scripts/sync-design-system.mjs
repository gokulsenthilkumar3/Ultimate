import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createRequire } from 'node:module';

// Keep adapters inside each product so independent checkouts remain buildable.
const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(path.join(root, 'growthtrack-ultimate/package.json'));
const ts = require('typescript');
const source = await readFile(path.join(root, 'growthtrack-ultimate/src/design/tokens.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { tokens } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const vars = (values, prefix = '', unit = '') => Object.entries(values).map(([key, value]) => `  --gt-${prefix}${key.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}: ${value}${unit};`).join('\n');
const css = `/* Generated by npm run design:sync. Source: Ultimate src/design/tokens.ts v${tokens.version}. */
:root {
${vars(tokens.space, 'space-', 'px')}
${vars(tokens.radius, 'radius-', 'px')}
${vars(tokens.motion, 'motion-')}
${vars(tokens.shadow, 'shadow-')}
  --gt-font: ${tokens.typography.family};
  --gt-target: ${tokens.target.minimum}px;
${vars(tokens.themes.light)}
}
@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]):not(.light) {
${vars(tokens.themes.dark)}
} }
[data-theme="dark"], .dark {
${vars(tokens.themes.dark)}
}
[data-theme="light"], .light {
${vars(tokens.themes.light)}
}
:where(button, a, input, select, textarea):focus-visible { outline: 3px solid var(--gt-focus); outline-offset: 3px; }
:where(button, select, input:not([type="checkbox"]):not([type="radio"])) { min-height: var(--gt-target); }
.gt-surface { background: var(--gt-surface); color: var(--gt-text); border: 1px solid var(--gt-border); border-radius: var(--gt-radius-lg); box-shadow: var(--gt-shadow-card); }
@supports (backdrop-filter: blur(12px)) {
  .gt-glass { background: color-mix(in srgb, var(--gt-surface) 88%, transparent); backdrop-filter: blur(12px); }
}
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after { animation-duration: .01ms !important; animation-iteration-count: 1 !important; transition-duration: .01ms !important; scroll-behavior: auto !important; }
}
@media (forced-colors: active) { .gt-surface { border: 1px solid CanvasText; box-shadow: none; } }
`;
const targets = [
  'FinSync/apps/web/app/growthtrack-design.css',
  'FinSync/OxFin/ox-fin-web/src/app/growthtrack-design.css',
  'Family Connect/familyconnect/frontend/src/growthtrack-design.css',
  'Equity/NiftyLens/src/app/growthtrack-design.css',
  'Forex/app/growthtrack-design.css',
];
for (const target of targets) {
  const absolute = path.join(root, target);
  if (process.argv.includes('--check')) {
    const current = await readFile(absolute, 'utf8').catch(() => '');
    if (current !== css) throw new Error(`Design adapter is stale: ${target}. Run npm run design:sync.`);
  } else await writeFile(absolute, css);
}
console.log(`Design ${tokens.version}: ${targets.length} adapters ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
