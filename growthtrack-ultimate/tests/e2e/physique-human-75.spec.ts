import {test,expect} from './foundation-fixture';
import {setupHumanViewer,bodySurface,paintedCanvas} from './helpers/human-viewer';

test('articulated hands and toes move, save independently, reload and restore neutral inspection',async({page})=>{
  const {canvas,targets,errors}=await setupHumanViewer(page,'reduce');
  await page.getByRole('tab',{name:'Pose',exact:true}).click();await page.getByRole('checkbox',{name:'Use saved pose'}).check();
  await page.getByRole('combobox',{name:'Left hand shape'}).selectOption('fist');
  await page.getByRole('slider',{name:'Right toes curl',exact:true}).fill('0.5');await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas)).pose.digits.leftHand?.shape).toBe('fist');
  await expect.poll(()=>targets().viewerPreferences.poseStudio?.current.digits?.rightFoot?.curl).toBe(.5);
  const posed=(await bodySurface(canvas)).pose.rotations.LeftIndex2;
  expect(Math.hypot(...posed.slice(0,3))).toBeGreaterThan(.3);
  expect((await bodySurface(canvas)).surfaceParts.find((p:any)=>p.part==='nails')).toMatchObject({visible:true,nails:20});
  const modes=page.getByRole('group',{name:'Comparison mode',exact:true});
  await modes.getByRole('button',{name:'Goal',exact:true}).click();await page.getByRole('checkbox',{name:'Use saved pose'}).check();
  await page.getByRole('combobox',{name:'Left hand shape'}).selectOption('point');
  await expect.poll(()=>targets().viewerPreferences.poseStudio?.goal.digits?.leftHand?.shape).toBe('point');
  expect(targets().viewerPreferences.poseStudio.current.digits.leftHand.shape).toBe('fist');
  await modes.getByRole('button',{name:'Current',exact:true}).click();
  await page.getByRole('button',{name:'Side',exact:true}).click();await canvas.scrollIntoViewIfNeeded();
  await paintedCanvas(canvas,test.info().outputPath('milestone-75-articulation-side.png'));
  await page.reload();await page.getByRole('tab',{name:'Pose',exact:true}).click();await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas))?.pose?.digits?.leftHand?.shape,{timeout:45000}).toBe('fist');
  await page.getByRole('tab',{name:'Measure',exact:true}).click();await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas)).pose.active).toBe(false);
  expect((await bodySurface(canvas)).pose.rotations.LeftIndex2.slice(0,3).every((v:number)=>Math.abs(v)<1e-7)).toBe(true);
  await page.getByRole('tab',{name:'Pose',exact:true}).click();await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas)).pose.digits.leftHand.shape).toBe('fist');
  await page.getByRole('button',{name:'Left hand',exact:true}).click();
  await paintedCanvas(canvas,test.info().outputPath('milestone-75-hand-close.png'));
  await page.getByRole('button',{name:'Right foot',exact:true}).click();
  await paintedCanvas(canvas,test.info().outputPath('milestone-75-toes-close.png'));
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('combobox',{name:'Left hand shape'}).scrollIntoViewIfNeeded();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.locator('.chamber-editor').screenshot({path:test.info().outputPath('milestone-75-controls-mobile.png')});
  expect(errors).toEqual([]);
});

test('pointer reach dragging saves the actual target, locks the camera and cancels with Escape',async({page})=>{
  const {canvas,targets,errors}=await setupHumanViewer(page,'reduce');
  await page.getByRole('tab',{name:'Pose',exact:true}).click();await page.getByRole('checkbox',{name:'Use saved pose'}).check();await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas)).poseHandles?.filter((h:any)=>h.visible).length).toBe(4);
  const point=async()=>{const handle=(await bodySurface(canvas)).poseHandles.find((h:any)=>h.id==='leftWrist'),box=(await canvas.boundingBox())!;return {x:box.x+box.width*handle.x,y:box.y+box.height*handle.y};};
  const originalCamera=await canvas.getAttribute('data-camera-position'),start=await point();
  await page.mouse.move(start.x,start.y);await page.mouse.down();await page.mouse.move(start.x-18,start.y-45,{steps:8});await page.mouse.up();
  await expect.poll(()=>targets().viewerPreferences.poseStudio?.current.targets.leftWrist).toBeTruthy();
  await expect.poll(async()=>(await bodySurface(canvas)).pose.limbs.leftWrist.error).toBeLessThan(.001);
  expect(await canvas.getAttribute('data-camera-position')).toBe(originalCamera);
  const saved=targets().viewerPreferences.poseStudio.current.targets.leftWrist;
  const second=await point();await page.mouse.move(second.x,second.y);await page.mouse.down();await page.mouse.move(second.x,second.y+35,{steps:5});
  await page.keyboard.press('Escape');await page.mouse.up();
  await expect.poll(()=>targets().viewerPreferences.poseStudio.current.targets.leftWrist).toEqual(saved);
  await page.reload();await page.getByRole('tab',{name:'Pose',exact:true}).click();await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas))?.pose?.targets?.leftWrist,{timeout:45000}).toEqual(saved);
  expect(errors).toEqual([]);
});

test('micro detail and eye layers render with authored resources, save, blink and export safely',async({page})=>{
  const {canvas,targets,errors}=await setupHumanViewer(page,'reduce');
  await page.getByRole('tab',{name:'Skin',exact:true}).click();await page.getByRole('slider',{name:'Pore detail',exact:true}).fill('0.85');
  await page.getByRole('button',{name:'Face',exact:true}).click();await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas)).microDetail.strength).toBe(.85);
  await expect.poll(()=>targets().appearanceMetrics.skinMicroDetail).toBe(.85);
  const body=await bodySurface(canvas);expect(body.microDetail.tile).toBe(true);
  expect(body.morphRig).toMatchObject({method:'asset-measured-joint-offsets',joints:79});
  expect(body.surfaceParts.find((p:any)=>p.part==='cornea')).toMatchObject({visible:true,ior:1.376});
  const detailed=await paintedCanvas(canvas,test.info().outputPath('milestone-75-layered-eye.png'));
  await page.getByRole('slider',{name:'Pore detail',exact:true}).fill('0');await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas)).microDetail.strength).toBe(0);
  expect((await paintedCanvas(canvas)).toString('base64')).not.toBe(detailed.toString('base64'));
  await page.getByRole('slider',{name:'Pore detail',exact:true}).fill('0.85');
  await page.getByRole('tab',{name:'Face',exact:true}).click();await page.getByRole('slider',{name:'Blink',exact:true}).press('End');await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas)).surfaceParts.find((p:any)=>p.part==='cornea').visible).toBe(false);
  await paintedCanvas(canvas,test.info().outputPath('milestone-75-closed-eye.png'));
  const downloading=page.waitForEvent('download');await page.getByRole('button',{name:'Export',exact:true}).click();await (await downloading).saveAs(test.info().outputPath('milestone-75-protected-export.png'));
  await page.reload();await page.getByRole('tab',{name:'Skin',exact:true}).click();await expect(page.getByRole('slider',{name:'Pore detail',exact:true})).toHaveValue('0.85');
  expect(errors).toEqual([]);
});
