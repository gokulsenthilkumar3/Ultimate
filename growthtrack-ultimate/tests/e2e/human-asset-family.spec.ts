import {test,expect,OWNER,emptyState} from './foundation-fixture';
import path from 'node:path';

test('human candidate loads a public GLB first, reveals native tissue and stays covered after reload',async({page})=>{
  test.setTimeout(120000);
  const errors:string[]=[],privateRequests:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(/Shader Error|VALIDATE_STATUS|gl.getProgramInfoLog/.test(m.text()))errors.push(m.text());});
  page.on('request',request=>{if(/human-r2-private/.test(request.url()))privateRequests.push(request.url());});
  const body={heightCm:175,weightKg:74,bodyFatPct:19,waistCm:82,chestCm:99,hipsCm:96,shouldersCm:112,armsCm:33,neckCm:37,modelPreset:'male',biologicalSex:'male',modelVersion:'human-r2'};
  await page.route(url=>url.pathname==='/api/state',route=>route.fulfill({json:{...emptyState(),user:{...OWNER,dob:'1990-01-01'},bodyProfile:body}}));
  await page.route(url=>url.pathname==='/api/body-profile',route=>route.fulfill({json:{...body,...route.request().postDataJSON()}}));
  await page.route(url=>url.pathname==='/api/physique_targets',route=>route.fulfill({json:route.request().method()==='GET'?{}:route.request().postDataJSON()}));
  await page.setViewportSize({width:1440,height:1050});
  await page.goto('/wellness/physique?view=3d');
  const canvas=page.locator('.chamber-canvas-wrap canvas');
  await canvas.scrollIntoViewIfNeeded();
  await expect(canvas).toHaveAttribute('data-camera-position',/.+/,{timeout:45000});
  await expect(page.getByRole('button',{name:'Use reviewed model',exact:true})).toBeVisible();
  expect(privateRequests).toEqual([]);
  await canvas.screenshot({path:path.resolve('.tmp/human-r2/browser-public.png')});
  await page.getByRole('tablist',{name:'Avatar editor'}).getByRole('tab',{name:'Anatomy',exact:true}).click();
  const reveal=page.getByRole('button',{name:'Anatomical mode',exact:true});
  await expect(reveal).toBeEnabled({timeout:30000});await reveal.click();
  await expect.poll(()=>privateRequests.length).toBeGreaterThan(0);
  await expect(page.getByRole('status').filter({hasText:'Loading anatomy'})).toHaveCount(0,{timeout:30000});
  await expect(page.getByRole('alert').filter({hasText:'Anatomy could not be loaded'})).toHaveCount(0);
  await page.getByLabel('Resting length current (cm)',{exact:true}).fill('12');
  await page.getByLabel('Resting length current (cm)',{exact:true}).press('Tab');
  await canvas.screenshot({path:path.resolve('.tmp/human-r2/browser-native.png')});
  await page.getByRole('button',{name:'Wear underwear',exact:true}).click();
  await expect(reveal).toHaveAttribute('aria-pressed','false');
  await page.reload();await canvas.scrollIntoViewIfNeeded();
  await expect(canvas).toHaveAttribute('data-camera-position',/.+/,{timeout:45000});
  const count=privateRequests.length;
  await page.getByRole('tablist',{name:'Avatar editor'}).getByRole('tab',{name:'Anatomy',exact:true}).click();
  await expect(page.getByRole('button',{name:'Anatomical mode',exact:true})).toHaveAttribute('aria-pressed','false');
  expect(privateRequests.length).toBe(count);
  expect(errors).toEqual([]);
});
