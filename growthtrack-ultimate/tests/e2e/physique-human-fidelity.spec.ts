import { test, expect } from './foundation-fixture';
import { setupHumanViewer as setup, surfaces, bodySurface } from './helpers/human-viewer';

test('skin edits retain authored textures and full blinks close actual eyelids', async ({ page }) => {
  const { canvas, errors } = await setup(page, 'reduce');
  const initial = await surfaces(canvas);
  expect(initial.find(item => item.eyelids)).toMatchObject({ material: 'MeshPhysicalMaterial', emissive: 0 });
  expect(initial.find(item => item.eyelids).eyelids.moved).toBeGreaterThan(20);
  const brows = initial.find(item => item.name === 'GrowthTrackEyebrows').surfaceBinding;
  expect(brows.bound / brows.total).toBeGreaterThan(.95);
  expect(initial.find(item=>item.name==='GrowthTrackHair').triangles).toBe(3344);
  expect(initial.find(item=>item.name==='GrowthTrackEyelashes').triangles).toBe(368);
  await canvas.screenshot({ path: test.info().outputPath('human-full-body.png') });
  await page.getByRole('button', { name: 'Face', exact: true }).click();
  await page.getByRole('tab', { name: 'Skin', exact: true }).click();
  for (const [label, color] of [['Very Light', 'e8c2ad'], ['Light', 'd8ac91'], ['Medium', 'c69578'], ['Brown', '825941'], ['Dark', '51382c'], ['Olive', 'ac7d63']]) {
    await page.getByRole('button', { name: label, exact: true }).click();
    await canvas.scrollIntoViewIfNeeded();
    await expect.poll(async () => (await bodySurface(canvas)).baseColor).toBe(color);
    const current = await surfaces(canvas);
    for (const original of initial) {
      const applied = current.find(item => item.name === original.name);
      expect(applied.map).toBe(original.map);
      expect(applied.normalMap).toBe(original.normalMap);
    }
  }
  const balancedGeometry=(await bodySurface(canvas)).geometry;
  await page.getByRole('tab', { name: 'View', exact: true }).click();
  await page.getByLabel('Model quality', { exact: true }).selectOption('high');
  await canvas.scrollIntoViewIfNeeded();
  await expect(canvas).toHaveAttribute('data-quality-tier','HIGH');
  await expect.poll(async()=>{const body=await bodySurface(canvas);return Boolean(body?.eyelids && body.geometry!==balancedGeometry);},{timeout:30000}).toBe(true);
  await page.getByRole('tab', { name: 'Face', exact: true }).click();
  await page.getByRole('button', { name: 'Face', exact: true }).click();
  await canvas.scrollIntoViewIfNeeded();
  await expect(canvas).toHaveAttribute('data-camera-focus', 'head');
  await expect.poll(async()=>{const body=await bodySurface(canvas);return Boolean(body?.geometry && await canvas.getAttribute('data-camera-region-geometry')===body.geometry);},{timeout:15000}).toBe(true);
  await page.evaluate(()=>new Promise<void>(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve()))));
  await expect.poll(async()=>Number(await canvas.getAttribute('data-camera-distance'))-Number(await canvas.getAttribute('data-camera-min-distance'))).toBeGreaterThanOrEqual(-.001);
  await expect.poll(async () => (await bodySurface(canvas)).idle.active).toBe(false);
  await canvas.screenshot({ path: test.info().outputPath('human-face.png') });
  const open = (await canvas.screenshot()).toString('base64');
  await page.getByRole('slider', { name: 'Blink', exact: true }).press('End');
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => (await bodySurface(canvas)).blink).toBeGreaterThan(.99);
  expect((await surfaces(canvas)).find(item => item.name === 'GrowthTrackEyes').visible).toBe(true);
  const shut = await canvas.screenshot({ path: test.info().outputPath('human-blink.png') });
  expect(shut.toString('base64')).not.toBe(open);
  await page.getByRole('slider', { name: 'Blink', exact: true }).press('Home');
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => (await bodySurface(canvas)).blink).toBeLessThan(.01);
  const highGeometry=(await bodySurface(canvas)).geometry;
  await page.getByRole('tab', { name: 'View', exact: true }).click();
  await page.getByLabel('Model quality', { exact: true }).selectOption('performance');
  await canvas.scrollIntoViewIfNeeded();
  await expect(canvas).toHaveAttribute('data-quality-tier','LOW');
  await expect.poll(async()=>{const body=await bodySurface(canvas);return Boolean(body?.geometry && body.geometry!==highGeometry && await canvas.getAttribute('data-camera-region-geometry')===body.geometry);},{timeout:30000}).toBe(true);
  await expect.poll(async () => Boolean((await bodySurface(canvas)).map)).toBe(true);
  await page.setViewportSize({ width: 390, height: 844 });
  await canvas.scrollIntoViewIfNeeded();
  await canvas.screenshot({ path: test.info().outputPath('human-face-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});

test('natural motion drives the rendered figure and respects saved choice, measurement and reduced motion', async ({ page }) => {
  const { canvas, errors, targets } = await setup(page, 'no-preference');
  await page.getByRole('tab', { name: 'View', exact: true }).click();
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => (await bodySurface(canvas)).idle.active).toBe(true);
  const first = (await bodySurface(canvas)).idle;
  const firstScale = (await bodySurface(canvas)).breathingScale;
  await expect.poll(async () => (await bodySurface(canvas)).idle.breath).not.toBe(first.breath);
  await expect.poll(async () => (await bodySurface(canvas)).breathingScale).not.toEqual(firstScale);
  await expect.poll(async () => (await surfaces(canvas)).find(item => item.gaze)?.gaze.some((value: number) => Math.abs(value) > .0001), { timeout: 15000 }).toBe(true);
  const modes=page.getByRole('group',{name:'Comparison mode',exact:true});
  await modes.getByRole('button',{name:'Goal',exact:true}).click();
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await surfaces(canvas)).filter(item=>item.eyelids).every(item=>item.idle?.active===false)).toBe(true);
  await modes.getByRole('button',{name:'Compare',exact:true}).click();
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await surfaces(canvas)).filter(item=>item.eyelids).length).toBe(2);
  await expect.poll(async()=>(await surfaces(canvas)).filter(item=>item.eyelids).every(item=>item.idle?.active===false)).toBe(true);
  await modes.getByRole('button',{name:'Current',exact:true}).click();
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas)).idle.active).toBe(true);
  const downloading=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export',exact:true}).click();
  const download=await downloading;
  expect(download.suggestedFilename()).toMatch(/\.png$/);
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async()=>(await bodySurface(canvas)).idle.active).toBe(true);
  await page.getByLabel('Natural idle motion', { exact: true }).uncheck();
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => (await bodySurface(canvas)).idle).toMatchObject({ active: false, breath: 0, gaze: { yaw: 0, pitch: 0 } });
  await expect.poll(async () => (await bodySurface(canvas)).breathingScale).toEqual([1, 1, 1]);
  await expect.poll(() => targets().viewerPreferences?.naturalMotion).toBe(false);
  await page.reload();
  await canvas.scrollIntoViewIfNeeded();
  await expect(canvas).toHaveAttribute('data-camera-position', /.+/, { timeout: 45000 });
  await page.getByRole('tab', { name: 'View', exact: true }).click();
  await expect(page.getByLabel('Natural idle motion', { exact: true })).not.toBeChecked();
  await page.getByLabel('Natural idle motion', { exact: true }).check();
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => (await bodySurface(canvas)).idle.active).toBe(true);
  await page.getByRole('tab', { name: 'Measure', exact: true }).click();
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => (await bodySurface(canvas)).idle.active).toBe(false);
  await page.getByRole('tab', { name: 'View', exact: true }).click();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => (await bodySurface(canvas)).idle.active).toBe(false);
  expect(errors).toEqual([]);
});

test('face, hair and eyelids remain intact from oblique views with a sky and skin layers', async ({ page }) => {
  const { canvas, errors } = await setup(page, 'reduce', { skinTone: 'III', skinColor: '#c69578', skinTan: .6, skinTanPattern: 'tank' });
  await page.getByRole('tab', { name: 'View', exact: true }).click();
  await page.getByLabel('Model background', { exact: true }).selectOption('space');
  await page.getByLabel('Space sky', { exact: true }).selectOption('nebula');
  await canvas.scrollIntoViewIfNeeded();
  await expect(canvas).toHaveAttribute('data-space-sky', 'nebula');
  await page.getByRole('button', { name: 'Face', exact: true }).click();
  await page.getByRole('tab', { name: 'Face', exact: true }).click();
  await canvas.scrollIntoViewIfNeeded();
  await expect(canvas).toHaveAttribute('data-camera-focus', 'head');
  const bounds = (await canvas.boundingBox())!;
  await page.mouse.move(bounds.x + bounds.width * .5, bounds.y + bounds.height * .5);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width * .5 + 75, bounds.y + bounds.height * .5, { steps: 12 });
  await page.mouse.up();
  await expect.poll(async () => Math.abs(Number(await canvas.getAttribute('data-camera-azimuth')))).toBeGreaterThan(.2);
  await canvas.screenshot({ path: test.info().outputPath('review-20-face-oblique.png') });
  await page.getByRole('slider', { name: 'Blink', exact: true }).press('End');
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => (await bodySurface(canvas)).blink).toBeGreaterThan(.99);
  await canvas.screenshot({ path: test.info().outputPath('review-20-blink-oblique.png') });
  const face = await surfaces(canvas);
  for (const name of ['GrowthTrackEyes', 'GrowthTrackHair', 'GrowthTrackEyebrows', 'GrowthTrackEyelashes']) {
    // Closed lids deliberately hide the old lash cards to prevent penetration.
    expect(face.find(item => item.name === name)).toMatchObject({ visible: name !== 'GrowthTrackEyelashes', map: expect.any(String) });
  }
  await page.getByRole('slider', { name: 'Blink', exact: true }).press('Home');
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => (await surfaces(canvas)).find(item => item.name === 'GrowthTrackEyelashes')?.visible).toBe(true);
  await page.getByRole('button', { name: 'Full body', exact: true }).click();
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await canvas.scrollIntoViewIfNeeded();
  await expect.poll(async () => Math.abs(Number(await canvas.getAttribute('data-camera-azimuth')))).toBeGreaterThan(3);
  await canvas.screenshot({ path: test.info().outputPath('review-20-back.png') });
  expect((await bodySurface(canvas)).tanPattern).toBe('tank');
  expect(errors).toEqual([]);
});
