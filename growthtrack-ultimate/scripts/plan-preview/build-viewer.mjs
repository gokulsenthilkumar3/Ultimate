#!/usr/bin/env node
// Bundles docs/3d-plans/plan-assets/src/human-stage.mjs (+ three.js) into one classic script,
// docs/3d-plans/plan-assets/human-stage.js, exposing window.PlanStage. A classic script keeps
// the v4 plan page working when it is opened straight from disk (file://),
// where ES module imports are blocked by the browser.
//
//   node scripts/plan-preview/build-viewer.mjs
//
// Uses the app's pinned `three` and the `rolldown` that ships with Vite
// (run `npm ci` in growthtrack-ultimate first), or any directory you run this
// from that has both installed.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, '../..');
const repoRoot = path.resolve(appRoot, '..');
const lookup = [appRoot, process.cwd()].map(dir => path.join(dir, 'node_modules'));
const require = createRequire(path.join(appRoot, 'noop.js'));
let bundler;
for (const dir of lookup) { try { bundler = await import(pathToFileURL(require.resolve(path.join(dir, 'rolldown'))).href); break; } catch { /* try the next location */ } }
if (!bundler) throw new Error('rolldown was not found. Run `npm ci` in growthtrack-ultimate (Vite installs it) and retry.');
const threePackage = lookup.map(dir => path.join(dir, 'three', 'package.json')).find(file => fs.existsSync(file));
if (!threePackage) throw new Error('three was not found. Run `npm ci` in growthtrack-ultimate and retry.');
const threeVersion = JSON.parse(fs.readFileSync(threePackage, 'utf8')).version;

const outfile = path.join(appRoot, 'docs/3d-plans/plan-assets/human-stage.js');
const bundle = await bundler.rolldown({ input: path.join(appRoot, 'docs/3d-plans/plan-assets/src/human-stage.mjs'), transform: { target: 'es2020' } });
try {
  await bundle.write({
    file: outfile, minify: true, format: 'iife', name: 'PlanStage',
    banner: `/* Generated by growthtrack-ultimate/scripts/plan-preview/build-viewer.mjs from docs/3d-plans/plan-assets/src. Includes three.js v${threeVersion} (MIT). */`,
  });
} finally { await bundle.close(); }
console.log(`wrote ${path.relative(repoRoot, outfile)} (${(fs.statSync(outfile).size / 1024).toFixed(0)} KB, three ${threeVersion})`);
