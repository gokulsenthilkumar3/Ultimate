#!/usr/bin/env node
// Bundles plan-assets/src/human-stage.mjs (+ three.js) into one classic script,
// plan-assets/human-stage.js, exposing window.PlanStage. A classic script keeps
// the v4 plan page working when it is opened straight from disk (file://),
// where ES module imports are blocked by the browser.
//
//   node scripts/plan-preview/build-viewer.mjs
//
// Uses the app's pinned `three` and the `esbuild` that ships with Vite
// (run `npm ci` in growthtrack-ultimate first), or any directory you run this
// from that has both installed.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, '../..');
const repoRoot = path.resolve(appRoot, '..');
const lookup = [appRoot, process.cwd()].map(dir => path.join(dir, 'node_modules'));
const require = createRequire(path.join(appRoot, 'noop.js'));
let esbuild;
for (const dir of lookup) { try { esbuild = require(path.join(dir, 'esbuild')); break; } catch { /* try the next location */ } }
if (!esbuild) throw new Error('esbuild was not found. Run `npm ci` in growthtrack-ultimate (Vite installs it) and retry.');
const threePackage = lookup.map(dir => path.join(dir, 'three', 'package.json')).find(file => fs.existsSync(file));
if (!threePackage) throw new Error('three was not found. Run `npm ci` in growthtrack-ultimate and retry.');
const threeVersion = JSON.parse(fs.readFileSync(threePackage, 'utf8')).version;

const outfile = path.join(repoRoot, 'plan-assets/human-stage.js');
await esbuild.build({
  entryPoints: [path.join(repoRoot, 'plan-assets/src/human-stage.mjs')],
  bundle: true, minify: true, format: 'iife', globalName: 'PlanStage', target: 'es2020', legalComments: 'eof',
  nodePaths: lookup, outfile, logLevel: 'warning',
  banner: { js: `/* Generated by growthtrack-ultimate/scripts/plan-preview/build-viewer.mjs from plan-assets/src. Includes three.js v${threeVersion} (MIT; licence notices at the end of this file). */` },
});
console.log(`wrote ${path.relative(repoRoot, outfile)} (${(fs.statSync(outfile).size / 1024).toFixed(0)} KB, three ${threeVersion})`);
