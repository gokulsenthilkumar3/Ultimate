import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync('src/design/tokens.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext } }).outputText;
const { tokens } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const theme = values => Object.entries(values).map(([key, value]) => `  --gt-${key.replace(/[A-Z]/g, c => `-${c.toLowerCase()}`)}: ${value};`).join('\n');
fs.writeFileSync('src/styles/design-tokens.css', `/* Generated by scripts/build-design-tokens.mjs. Edit src/design/tokens.ts. */\n:root, [data-theme="dark"] {\n${theme(tokens.themes.dark)}\n  color-scheme: dark;\n}\n[data-theme="light"] {\n${theme(tokens.themes.light)}\n  color-scheme: light;\n}\n`);
